"""Generate a combinational positive-half sigmoid ROM (no writable state)."""
from decimal import Decimal, ROUND_HALF_EVEN, localcontext
from pathlib import Path
import argparse
import json


def coefficients():
    with localcontext() as ctx:
        ctx.prec = 80
        return [int((Decimal(65536) / (1 + (-Decimal(i) / 32).exp()))
                    .to_integral_value(rounding=ROUND_HALF_EVEN)) for i in range(256)]


def contents():
    values = coefficients()
    sv = ["// Generated by generate_lut.py; Decimal precision=80, RNE Q16.",
          "function automatic [16:0] sigmoid_positive_lut;",
          "    input [7:0] index;", "    begin", "        case (index)"]
    sv.extend(f"            8'd{i}: sigmoid_positive_lut = 17'd{v};"
              for i, v in enumerate(values))
    sv += ["            default: sigmoid_positive_lut = 17'd32768;",
           "        endcase", "    end", "endfunction", ""]
    return {"sigmoid_lut.svh": "\n".join(sv),
            "sigmoid_lut_q16.json": json.dumps({
                "positive_index": "g=i/32; i=0..255",
                "encoding": "unsigned 17-bit, value=raw/65536",
                "rounding": "nearest, ties to even; Decimal precision 80",
                "values": values}, indent=2) + "\n"}


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    root = Path(__file__).resolve().parent
    for name, expected in contents().items():
        path = root / name
        if args.check:
            assert path.read_bytes() == expected.encode("utf-8"), name
        else:
            path.write_bytes(expected.encode("utf-8"))
    print("LUT coefficients: " + ("verified" if args.check else "generated"))


if __name__ == "__main__":
    main()
