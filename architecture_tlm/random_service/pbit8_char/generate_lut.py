"""Deterministic case ROM, no real arithmetic in synthesizable RTL."""
import math
from pathlib import Path

ROOT = Path(__file__).resolve().parent

def probability(code):
    x = code / 8.0
    p = 1/(1+math.exp(-x)) if x >= 0 else math.exp(x)/(1+math.exp(x))
    return int(math.floor(256*p+0.5))

def render():
    lines = ['// Generated by generate_lut.py. signed drive8 / 8 is SIGMOID log odds.',
             '// q9=round_half_up(256*sigmoid(drive8/8)), same as service.SigmoidTable.',
             '// For p=(1+tanh(h))/2, supply log odds 2*h upstream.',
             'module pbit_sigmoid8_lut(input wire signed [7:0] drive8, output reg [8:0] q9);',
             '  always @* begin', '    case (drive8)']
    for u in range(256):
        lines.append("      8'h%02x: q9=9'd%d;" % (u,probability(u if u<128 else u-256)))
    return '\n'.join(lines+['      default: q9=9\'bx;', '    endcase', '  end', 'endmodule',''])

if __name__ == '__main__':
    (ROOT/'rtl/pbit_sigmoid8_lut.sv').write_bytes(render().encode())
