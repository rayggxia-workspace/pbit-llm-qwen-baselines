"""Export the completed Issue48 suffix sweep as PNG and standalone SVG.

Input is summarize_results.py's summary.json, never a pilot case/result.  No
formal figure is generated by --self-test: synthetic data is rendered in memory
with a SELF-TEST watermark.  This script does not read server logs or run models.
"""
from __future__ import annotations

import argparse
import copy
import hashlib
import io
import json
import math
import os
import platform
from pathlib import Path

BASE = Path(__file__).resolve().parent
os.environ["MPLCONFIGDIR"] = str(BASE / ".mplconfig")
import matplotlib

matplotlib.use("Agg")
import matplotlib.pyplot as plt
from matplotlib import font_manager
from matplotlib.ticker import ScalarFormatter

SAMPLES = (32, 64, 128, 256, 512, 1024)
IID_SAMPLES = (32, 128, 512)
DEFAULT_SOURCE = "11f1d6eea277"
EXPECTED_PROTOCOL = dict(context=2048, decode=128, examples=32, batch=8,
                         burn=16, spacing=4, budget_blocks=8, stride=1024,
                         target_fraction=0.3, protocol="suffix")


def choose_font():
    available = {font.name for font in font_manager.fontManager.ttflist}
    for name in ("Microsoft YaHei", "SimHei", "Noto Sans CJK SC"):
        if name in available:
            return name, True
    return "DejaVu Sans", False


def dependencies():
    font, chinese = choose_font()
    return dict(python=platform.python_version(), executable=os.sys.executable,
                matplotlib=matplotlib.__version__, backend=matplotlib.get_backend(),
                font=font, chinese_labels=chinese, installed_packages_modified=False)


def validate_summary(data, expected_source=DEFAULT_SOURCE):
    """Fail closed on partial stages, preflights, other protocols or missing seeds."""
    stage = str(data.get("stage", "")).lower()
    if "sweep" not in stage or any(word in stage for word in ("pilot", "preflight", "smoke")):
        raise ValueError("Only a completed formal sweep summary can generate the figure")
    if data.get("protocol") != "suffix" or data.get("scored_tokens_per_seed") != 4096:
        raise ValueError("This figure is for the fixed 4096-target WT2 suffix protocol")
    if data.get("completed_cases") != 34 or data.get("registered_cases") != 34:
        raise ValueError("Require all 34 registered cases; no partial sweep curve")
    if data.get("full_model_layers") != 24 or data.get("ffn") != "original":
        raise ValueError("Require all 24 decode layers with original FFN")
    if data.get("prefill") not in ("accurate SDPA", "original multi-token SDPA") or data.get("hardware_PPA_measured") is not False:
        raise ValueError("Require accurate prefill and explicitly non-hardware results")
    if data.get("model_weights_unchanged") is not True:
        raise ValueError("Missing model-weight preservation verification")
    source = data.get("source_commit", "")
    if expected_source and not source.startswith(expected_source):
        raise ValueError(f"Unexpected execution source {source!r}; expected prefix {expected_source}")
    # The original summarizer omits context; this script is explicitly pinned to
    # the registered 2K-initial-context suite.  Check added metadata when present.
    for key in ("initial_context", "context"):
        if key in data and data[key] != 2048:
            raise ValueError("Expected 2048 initial context, followed by 128 decode inputs")
    if "protocol_parameters" in data:
        parameters = data["protocol_parameters"]
        if not isinstance(parameters, dict):
            raise ValueError("protocol_parameters must be an object")
        for key, expected in EXPECTED_PROTOCOL.items():
            if parameters.get(key) != expected:
                raise ValueError(f"Unexpected protocol_parameters.{key}: {parameters.get(key)!r}; expected {expected!r}")
    groups = {}
    for row in data.get("groups", []):
        key = (row.get("mode"), row.get("selection"), row.get("samples"))
        if key in groups:
            raise ValueError(f"Duplicate summary group {key}")
        mean, sd = row.get("ppl_mean"), row.get("ppl_seed_population_sd")
        if not isinstance(mean, (int, float)) or not math.isfinite(mean) or mean <= 0:
            raise ValueError(f"Invalid PPL mean for {key}")
        if not isinstance(sd, (int, float)) or not math.isfinite(sd) or sd < 0:
            raise ValueError(f"Invalid population seed SD for {key}")
        if row.get("scored_tokens_per_seed") != 4096:
            raise ValueError(f"Wrong scored-token count for {key}")
        seeds = row.get("seeds", [])
        if len(set(seeds)) != len(seeds):
            raise ValueError(f"Duplicate seed for {key}")
        groups[key] = row

    def require(mode, sample, seeds):
        key = (mode, "fixed", sample)
        if key not in groups or set(groups[key]["seeds"]) != set(seeds):
            raise ValueError(f"Missing required fixed-budget group/seeds: {key}, {seeds}")
        return groups[key]

    ct = [require("screen_ising", sample, (0, 1, 2)) for sample in SAMPLES]
    iid = [require("screen_iid", sample, (0, 1, 2)) for sample in IID_SAMPLES]
    return dict(ctmc=ct, iid=iid, sdpa=require("sdpa", 128, (0,)),
                screen_exact=require("screen_exact", 128, (0, 1, 2)),
                digital_exact=require("digital_exact", 128, (0,)))


def make_figure(data, points, *, show_iid=True, show_digital_exact=False, synthetic=False):
    font, chinese = choose_font()
    plt.rcParams.update({"font.family": "sans-serif", "font.sans-serif": [font, "DejaVu Sans"],
                         "axes.unicode_minus": False, "svg.fonttype": "path", "font.size": 11})
    fig, ax = plt.subplots(figsize=(10.2, 6.6), layout=None)
    fig.subplots_adjust(left=0.10, right=0.97, top=0.79, bottom=0.23)
    title = "概率 QK 筛选＋有限时间 Ising：采样数与 PPL" if chinese else "Probabilistic QK screening + finite-time Ising: sample budget and PPL"
    fig.suptitle(title, x=0.10, y=0.96, ha="left", fontsize=16, weight="bold")
    fig.text(0.10, 0.885, "2K initial context, 4096 WT2 suffix targets/seed", fontsize=11)
    fig.text(0.10, 0.845, "24 decode layers; original FFN; accurate prefill; KV length 2048–2175", fontsize=10)

    ct = points["ctmc"]
    ax.errorbar(SAMPLES, [p["ppl_mean"] for p in ct],
                yerr=[p["ppl_seed_population_sd"] for p in ct],
                color="#125CA3", marker="o", markersize=6, linewidth=2.0,
                elinewidth=1.3, capsize=4, label="联合 CTMC：均值 ± seed 总体 SD" if chinese else "Joint CTMC: mean ± population seed SD", zorder=5)
    if show_iid:
        iid = points["iid"]
        ax.errorbar(IID_SAMPLES, [p["ppl_mean"] for p in iid],
                    yerr=[p["ppl_seed_population_sd"] for p in iid],
                    color="#087F75", marker="s", markersize=5, linestyle=":", linewidth=1.6,
                    elinewidth=1.1, capsize=3, label="同筛选＋IID（3 seeds）" if chinese else "Same screening + IID (3 seeds)", zorder=4)
    baseline = points["sdpa"]["ppl_mean"]
    ax.axhline(baseline, color="#505763", linestyle="--", linewidth=1.5,
               label=f"Matched original SDPA: {baseline:.5f}")
    exact = points["screen_exact"]
    mean, sd = exact["ppl_mean"], exact["ppl_seed_population_sd"]
    ax.axhspan(mean - sd, mean + sd, color="#D97706", alpha=0.08, linewidth=0)
    ax.axhline(mean, color="#D97706", linestyle="-.", linewidth=1.5,
               label=("同筛选＋准确 PV" if chinese else "Same screening + exact PV") + f": {mean:.5f}")
    if show_digital_exact:
        exact = points["digital_exact"]["ppl_mean"]
        ax.axhline(exact, color="#8B5FBF", linestyle=(0, (2, 3)), linewidth=1.2,
                   label=f"FP32 digital attention: {exact:.5f}")
    ax.set_xscale("log", base=2)
    ax.set_xticks(SAMPLES, [str(s) for s in SAMPLES])
    ax.xaxis.set_minor_locator(plt.NullLocator())
    ax.set_xlim(27, 1220)
    ax.set_xlabel("采样数 S / 每层每头每个 decode 查询" if chinese else "Samples S per head, layer, decode query")
    ax.set_ylabel("PPL（越低越好）" if chinese else "Perplexity (lower is better)")
    ax.yaxis.set_major_formatter(ScalarFormatter(useOffset=False))
    ax.ticklabel_format(axis="y", style="plain", useOffset=False)
    ax.grid(axis="y", color="#DCE1E6", linewidth=0.7)
    ax.set_axisbelow(True)
    ax.spines[["top", "right"]].set_visible(False)
    ax.legend(loc="best", fontsize=9, framealpha=0.94)
    foot = ("固定 8 块，最多 512 个候选；burn=16，gap=4（CTMC 时间单位）。\n"
            "误差为 3 个推理 seed 的总体标准差，不是语料置信区间；橙色带为准确 PV 的 seed SD。\n"
            "固定后缀评测，不是完整 WT2；行为级质量结果，不是芯片计时、能耗或面积。") if chinese else (
            "Fixed 8 blocks, at most 512 candidates; burn=16, gap=4 in CTMC time units.\n"
            "Bars: population SD over 3 inference seeds, not a corpus confidence interval; orange band: exact-PV seed SD.\n"
            "Fixed suffix evaluation, not full WT2. Behavioral quality, not chip timing, energy, or area.")
    fig.text(0.10, 0.135, foot, ha="left", va="top", fontsize=9, color="#515967", linespacing=1.6)
    fig.text(0.10, 0.015, f"Source {data['source_commit'][:12]} · Slurm {data.get('job_id', 'unknown')}", fontsize=8, color="#68717D")
    if synthetic:
        fig.text(0.5, 0.5, "SELF-TEST — SYNTHETIC", ha="center", fontsize=24, alpha=0.22, rotation=20)
    return fig


def self_test():
    data = dict(stage="sweep", protocol="suffix", scored_tokens_per_seed=4096,
                completed_cases=34, registered_cases=34, full_model_layers=24,
                ffn="original", prefill="accurate SDPA", hardware_PPA_measured=False,
                model_weights_unchanged=True, source_commit=DEFAULT_SOURCE + "0" * 28,
                job_id="SELF-TEST", groups=[])
    def add(mode, samples, mean, seeds):
        data["groups"].append(dict(mode=mode, selection="fixed", samples=samples,
            seeds=list(seeds), ppl_mean=mean, ppl_seed_population_sd=0.01 if len(seeds) == 3 else 0.,
            scored_tokens_per_seed=4096))
    add("sdpa", 128, 10., (0,)); add("digital_exact", 128, 10.01, (0,))
    add("screen_exact", 128, 10.03, (0, 1, 2))
    for s in SAMPLES: add("screen_ising", s, 10.03 + 6.0 / s, (0, 1, 2))
    for s in IID_SAMPLES: add("screen_iid", s, 10.03 + 4.0 / s, (0, 1, 2))
    points = validate_summary(data)
    checks = ["all six CTMC budgets and three IID controls accepted"]
    data.update(prefill="original multi-token SDPA", protocol_parameters=dict(EXPECTED_PROTOCOL))
    points = validate_summary(data)
    checks.append("new original-multi-token prefill and full protocol_parameters accepted")
    for key, expected in EXPECTED_PROTOCOL.items():
        bad = copy.deepcopy(data)
        bad["protocol_parameters"][key] = "full" if key == "protocol" else expected + 1
        try: validate_summary(bad)
        except ValueError: checks.append(f"reject changed protocol_parameters.{key}")
        else: raise AssertionError(f"Changed protocol parameter {key} accepted")
    bad = copy.deepcopy(data); del bad["protocol_parameters"]["spacing"]
    try: validate_summary(bad)
    except ValueError: checks.append("reject missing protocol_parameters.spacing")
    else: raise AssertionError("Missing protocol spacing accepted")
    for field, wrong in (("stage", "gpu_preflight"), ("completed_cases", 12),
                         ("scored_tokens_per_seed", 128), ("model_weights_unchanged", False)):
        bad = copy.deepcopy(data); bad[field] = wrong
        try: validate_summary(bad)
        except ValueError: checks.append(f"reject {field}={wrong}")
        else: raise AssertionError(f"Invalid {field} accepted")
    bad = copy.deepcopy(data); bad["groups"][-1]["seeds"] = [0]
    try: validate_summary(bad)
    except ValueError: checks.append("reject incomplete seed group")
    else: raise AssertionError("Incomplete seeds accepted")
    fig = make_figure(data, points, synthetic=True)
    buffers = {}
    for fmt in ("png", "svg"):
        memory = io.BytesIO()
        fig.savefig(memory, format=fmt, dpi=160,
                    metadata={"Creator": "Issue48 verified suffix PPL plot"})
        payload = memory.getvalue()
        assert payload.startswith(b"\x89PNG") if fmt == "png" else b"<svg" in payload[:1000]
        buffers[fmt] = len(payload)
    plt.close(fig)
    return dict(passed=True, checks=checks, in_memory_exports_bytes=buffers,
                synthetic_data_only=True, formal_figures_created=False, dependencies=dependencies())


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("summary", nargs="?", type=Path)
    parser.add_argument("--input", dest="input_summary", type=Path)
    parser.add_argument("--output", "--output-dir", dest="output_dir", type=Path, default=BASE / "figures")
    parser.add_argument("--expected-source", default=DEFAULT_SOURCE)
    parser.add_argument("--no-iid", action="store_true")
    parser.add_argument("--include-digital-exact", action="store_true")
    parser.add_argument("--self-test", action="store_true")
    parser.add_argument("--show-deps", action="store_true")
    args = parser.parse_args()
    if args.show_deps:
        print(json.dumps(dependencies(), ensure_ascii=False, indent=2)); return
    if args.self_test:
        print(json.dumps(self_test(), ensure_ascii=False, indent=2)); return
    if args.input_summary is not None:
        if args.summary is not None: parser.error("Use either the summary positional argument or --input")
        args.summary = args.input_summary
    if args.summary is None: parser.error("Provide the completed sweep's summary.json with --input or a positional argument")
    raw = args.summary.read_bytes(); data = json.loads(raw.decode("utf-8"))
    points = validate_summary(data, expected_source=args.expected_source)
    out = args.output_dir.resolve()
    if not out.is_relative_to(BASE): raise ValueError("Output must remain under this task output directory")
    names = [out / f"sampling_ppl.{ext}" for ext in ("png", "svg")]
    receipt_path = out / "plot_provenance.json"
    if any(p.exists() for p in names + [receipt_path]):
        raise FileExistsError("Refuse to overwrite prior plot artifacts; use a new output subdirectory")
    out.mkdir(parents=True, exist_ok=True)
    fig = make_figure(data, points, show_iid=not args.no_iid, show_digital_exact=args.include_digital_exact)
    for path in names: fig.savefig(path, dpi=240, metadata={"Creator": "Issue48 verified suffix PPL plot"})
    plt.close(fig)
    receipt = dict(summary=str(args.summary.resolve()), summary_sha256=hashlib.sha256(raw).hexdigest(),
                   source_commit=data["source_commit"], job_id=data.get("job_id"),
                   script_sha256=hashlib.sha256(Path(__file__).read_bytes()).hexdigest(),
                   protocol="2K initial context; 4096 WT2 suffix targets/seed; KV length 2048..2175",
                   protocol_parameters=data.get("protocol_parameters"), prefill=data["prefill"],
                   rng_scope=data.get("rng_scope"),
                   sample_prefix_scope="Nested prefixes apply only to a single sampler call with identical logits and RNG state; changing S may change later autoregressive states.",
                   population_seed_SD=True, corpus_confidence_interval=False,
                   hardware_PPA_measured=False, original_FFN=True, decode_layers=24,
                   include_iid=not args.no_iid, include_digital_exact=args.include_digital_exact,
                   groups_validated=points,
                   groups_plotted={key: value for key, value in points.items()
                                   if (key != "iid" or not args.no_iid)
                                   and (key != "digital_exact" or args.include_digital_exact)},
                   dependencies=dependencies(),
                   artifacts=[dict(path=str(p), bytes=p.stat().st_size,
                                   sha256=hashlib.sha256(p.read_bytes()).hexdigest()) for p in names])
    receipt_path.write_text(json.dumps(receipt, ensure_ascii=False, indent=2) + "\n", encoding="utf-8", newline="\n")
    print(json.dumps(dict(passed=True, artifacts=[str(p) for p in names], receipt=str(receipt_path)), ensure_ascii=False, indent=2))


if __name__ == "__main__":
    main()
